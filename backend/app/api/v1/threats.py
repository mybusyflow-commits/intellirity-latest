# Monotonic ID counter. IDs were previously derived from len(store),
# which repeats once the store hits its size cap. A counter never repeats.
_threat_id_seq = count(4822)


def add_threat_event(threat_type: str, severity: str, source: str, description: str,
                     origin: str = "detection", owner: str = "demo") -> dict:
    """Record a threat.

    origin="detection"  — produced by a real engine on real traffic
    origin="synthetic"  — generated by the demo feed (clearly marked)
    origin="sample"     — static seed row
    """
    threat = {
        "id": f"EVT-{next(_threat_id_seq)}",
        "threat_type": threat_type,
        "severity": severity,
        "source": source,
        "description": description,
        "is_resolved": False,
        "created_at": datetime.now(timezone.utc),
        "origin": origin,
        "owner": owner,
    }
    _memory_threats.insert(0, threat)
    return threat


def get_threats_store() -> list[dict]:
    return _memory_threats


PAGE_SIZE = 20


def _paginate(items: list[dict], limit: Optional[int], cursor: Optional[str]):
    """Stable newest-first paging by unique id. New inserts land at the
    front, so 'older than cursor' slices never repeat or skip (no deletes)."""
    if not limit or limit <= 0:
        return {"items": items, "next_cursor": None, "has_more": False}
    limit = min(limit, 100)
    start = 0
    if cursor:
        for i, t in enumerate(items):
            if t.get("id") == cursor:
                start = i + 1
                break
    page = items[start:start + limit]
    next_cursor = page[-1]["id"] if page and start + limit < len(items) else None
    return {
        "items": page,
        "next_cursor": next_cursor,
        "has_more": next_cursor is not None,
    }


@router.get("")
@router.get("/")
async def list_threats(
    status: Optional[str] = None,
    severity: Optional[str] = None,
    limit: Optional[int] = None,
    cursor: Optional[str] = None,
    user: dict = Depends(require_user),
):
    # Production: only this tenant's detections. Open mode (tests / local
    # operator, user == {}) keeps the legacy view of the seeded rows.
    owner = _owner(user) if user else None
    results = (
        [t for t in _memory_threats if t.get("owner") == owner]
        if owner
        else list(_memory_threats)
    )
    if status == "active":
        results = [t for t in results if not t["is_resolved"]]
    elif status == "resolved":
        results = [t for t in results if t["is_resolved"]]

    if severity:
        results = [t for t in results if t["severity"].lower() == severity.lower()]

    # Legacy shape (no limit): plain list, unchanged for existing clients.
    if not limit:
        return [ThreatDetectionResponse(**t).model_dump() for t in results]
    page = _paginate(results, limit, cursor)
    page["items"] = [ThreatDetectionResponse(**t).model_dump() for t in page["items"]]
    return page


@router.get("/{threat_id}", response_model=ThreatDetectionResponse)
async def get_threat(threat_id: str, user: dict = Depends(require_user)):
    owner = _owner(user) if user else None
    for t in _memory_threats:
        if t["id"] == threat_id and (owner is None or t.get("owner") == owner):
            return ThreatDetectionResponse(**t)
    raise HTTPException(status_code=404, detail=f"Threat {threat_id} not found")


@router.post("/{threat_id}/resolve", response_model=ThreatDetectionResponse)
async def resolve_threat(threat_id: str, user: dict = Depends(require_user)):
    owner = _owner(user) if user else None
    for t in _memory_threats:
        if t["id"] == threat_id and (owner is None or t.get("owner") == owner):
            t["is_resolved"] = True
            return ThreatDetectionResponse(**t)
    raise HTTPException(status_code=404, detail=f"Threat {threat_id} not found")

